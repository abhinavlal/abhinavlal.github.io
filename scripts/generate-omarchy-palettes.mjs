// Regenerates src/data/omarchy-palettes.ts and src/styles/omarchy-palettes.css
// — the six ANSI colours (color1–color6) of each Omarchy theme — from a
// directory of <slug>.toml files or an Omarchy themes/ checkout.
//
//   node scripts/generate-omarchy-palettes.mjs /tmp/omarchy/themes
import { existsSync, readdirSync, readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";

const dir = process.argv[2];
if (!dir) {
  console.error("usage: node scripts/generate-omarchy-palettes.mjs <dir>");
  process.exit(1);
}

const KEYS = ["red", "green", "yellow", "blue", "magenta", "cyan"];

const parseToml = text => {
  const out = {};
  for (const line of text.split("\n")) {
    const m = line.match(/^\s*([a-z0-9_]+)\s*=\s*"([^"]*)"/);
    if (m) out[m[1]] = m[2].toLowerCase();
  }
  return out;
};

const palettes = {};
for (const entry of readdirSync(dir, { withFileTypes: true }).sort()) {
  const slug = entry.name.replace(/\.toml$/, "");
  const file = entry.isDirectory()
    ? join(dir, entry.name, "colors.toml")
    : join(dir, entry.name);
  if (!existsSync(file)) continue;
  const c = parseToml(readFileSync(file, "utf8"));
  if (!c.color6) continue;
  palettes[slug] = Object.fromEntries(
    KEYS.map((k, i) => [k, c[`color${i + 1}`]])
  );
}

const ts = `// Generated by scripts/generate-omarchy-palettes.mjs — do not edit by hand.
// ANSI colours 1–6 of each theme's colors.toml in https://github.com/basecamp/omarchy.
export type Palette = Record<
  "red" | "green" | "yellow" | "blue" | "magenta" | "cyan",
  string
>;

export const OMARCHY_PALETTES: Record<string, Palette> = ${JSON.stringify(palettes, null, 2)};
`;

const css =
  `/* Generated by scripts/generate-omarchy-palettes.mjs — do not edit by hand. */\n` +
  Object.entries(palettes)
    .map(
      ([slug, p]) =>
        `[data-theme="${slug}"] {\n` +
        KEYS.map(k => `  --${k}: ${p[k]};`).join("\n") +
        `\n}`
    )
    .join("\n\n") +
  "\n";

writeFileSync("src/data/omarchy-palettes.ts", ts);
writeFileSync("src/styles/omarchy-palettes.css", css);
console.log(`wrote ${Object.keys(palettes).length} palettes`);
