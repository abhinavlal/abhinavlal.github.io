// Regenerates src/data/omarchy-themes.ts and src/styles/omarchy-themes.css
// from the colors.toml files in an Omarchy checkout.
//
//   git clone --depth 1 https://github.com/basecamp/omarchy /tmp/omarchy
//   node scripts/generate-omarchy-themes.mjs /tmp/omarchy/themes
import { readdirSync, readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";

const themesDir = process.argv[2];
if (!themesDir) {
  console.error("usage: node scripts/generate-omarchy-themes.mjs <omarchy>/themes");
  process.exit(1);
}

const parseToml = text => {
  const out = {};
  for (const line of text.split("\n")) {
    const m = line.match(/^\s*([a-z_]+)\s*=\s*"([^"]*)"/);
    if (m) out[m[1]] = m[2].toLowerCase();
  }
  return out;
};

const titleCase = slug =>
  slug
    .split("-")
    .map(w => (/^\d/.test(w) ? w : w[0].toUpperCase() + w.slice(1)))
    .join(" ");

const themes = readdirSync(themesDir, { withFileTypes: true })
  .filter(d => d.isDirectory())
  .map(d => d.name)
  .sort()
  .map(slug => {
    const c = parseToml(readFileSync(join(themesDir, slug, "colors.toml"), "utf8"));
    return {
      slug,
      name: titleCase(slug),
      mode: c.mode === "light" ? "light" : "dark",
      colors: {
        background: c.background,
        foreground: c.foreground,
        accent: c.accent,
        accentForeground: c.mode === "light" ? c.background : c.darker_background,
        muted: c.selection,
        mutedForeground: c.dark_foreground,
        border: c.muted,
        surface: c.lighter_background,
      },
    };
  });

const ts = `// Generated by scripts/generate-omarchy-themes.mjs — do not edit by hand.
// Palettes come from the colors.toml of each theme in https://github.com/basecamp/omarchy.
export type ThemeMode = "light" | "dark";

export interface OmarchyTheme {
  slug: string;
  name: string;
  mode: ThemeMode;
  colors: {
    background: string;
    foreground: string;
    accent: string;
    accentForeground: string;
    muted: string;
    mutedForeground: string;
    border: string;
    surface: string;
  };
}

export const OMARCHY_THEMES: OmarchyTheme[] = ${JSON.stringify(themes, null, 2)};

export const DEFAULT_DARK_THEME = "tokyo-night";
export const DEFAULT_LIGHT_THEME = "flexoki-light";
`;

const css =
  `/* Generated by scripts/generate-omarchy-themes.mjs — do not edit by hand. */\n` +
  themes
    .map(
      t => `[data-theme="${t.slug}"] {
  color-scheme: ${t.mode};
  --background: ${t.colors.background};
  --foreground: ${t.colors.foreground};
  --accent: ${t.colors.accent};
  --accent-foreground: ${t.colors.accentForeground};
  --muted: ${t.colors.muted};
  --muted-foreground: ${t.colors.mutedForeground};
  --border: ${t.colors.border};
  --surface: ${t.colors.surface};
}`
    )
    .join("\n\n") +
  "\n";

writeFileSync("src/data/omarchy-themes.ts", ts);
writeFileSync("src/styles/omarchy-themes.css", css);
console.log(`wrote ${themes.length} themes`);
